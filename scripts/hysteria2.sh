#!/usr/bin/env bash
# Hysteria2 – https://github.com/itsnotkubrick/3X-UI_KIT
#
# Отдельный установщик Hysteria2 больше не поддерживается: Hysteria2 входит в основную
# установку 3X-UI KIT (scripts/3x-ui.sh). Файл оставлен, чтобы старая команда `hy2 update`
# получила из подписанного релиза понятное сообщение. Ничего не ставит, не удаляет и не
# останавливает: сервер Hysteria2, установленный раньше, продолжает работать как был.
# Код выхода 1 при любом запуске (и при `__update_binary`) – старый `hy2 update` на нём
# останавливается и не заменяет команду hy2.

KIT_VERSION="1.2"

cat >&2 <<'MSG'
Отдельный установщик Hysteria2 больше не поддерживается.
Сервер Hysteria2 продолжает работать как раньше, но не обновляется этим скриптом.
Hysteria2 входит в основную установку 3X-UI KIT (один из 11 протоколов).
Если нужен только Hysteria2 без панели – официальный установщик:
  bash <(curl -fsSL https://get.hy2.sh/)
MSG
exit 1
